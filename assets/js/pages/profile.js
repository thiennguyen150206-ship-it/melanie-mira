async function renderMyAddresses() {
  try {
    const result = await fetchMyAddresses();

    if (!result.success) {
      $("#profileAddressList").html(
        createProfileEmptyBox(pText("cannotLoadAddress")),
      );
      return;
    }

    currentAddresses = result.data;

    if (result.data.length === 0) {
      $("#profileAddressList").html(createProfileEmptyBox(pText("noAddress")));
      return;
    }

    let html = "";

    for (let i = 0; i < result.data.length; i++) {
      html += createAddressItem(result.data[i]);
    }

    $("#profileAddressList").html(html);
  } catch (error) {
    $("#profileAddressList").html(
      createProfileEmptyBox(pText("cannotConnect")),
    );
  }
}

