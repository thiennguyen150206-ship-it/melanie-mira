function getCurrentProfileLanguage() {
  const savedLanguage = localStorage.getItem("language");

  if (savedLanguage === "vi") {
    return "vi";
  }

  return "en";
}

function pText(key) {
  const currentLanguage = getCurrentProfileLanguage();
  return (
    profileTranslations[currentLanguage][key] ||
    profileTranslations.en[key] ||
    key
  );
}

