function formatProfileMoney(price) {
  return Number(price).toLocaleString("vi-VN") + "đ";
}

function formatProfileDate(dateValue) {
  if (!dateValue) {
    return pText("unknown");
  }

  const date = new Date(dateValue);

  if (Number.isNaN(date.getTime())) {
    return pText("unknown");
  }

  const currentLanguage = getCurrentProfileLanguage();
  const locale = currentLanguage === "vi" ? "vi-VN" : "en-GB";

  return date.toLocaleString(locale, {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}

function escapeHtml(value) {
  if (value === null || value === undefined) {
    return "";
  }

  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function getOrderStatusText(status) {
  const orderStatus = String(status || "")
    .trim()
    .toLowerCase();

  if (orderStatus === "pending") {
    return pText("pending");
  }

  if (orderStatus === "confirmed") {
    return pText("confirmed");
  }

  if (orderStatus === "shipping") {
    return pText("shipping");
  }

  if (orderStatus === "completed") {
    return pText("completed");
  }

  if (orderStatus === "cancelled") {
    return pText("cancelled");
  }

  return status;
}

function getOrderStatusClass(status) {
  let orderStatus = String(status || "")
    .trim()
    .toLowerCase();

  if (orderStatus === "pending") {
    return "status-pending";
  }

  if (orderStatus === "confirmed") {
    return "status-confirmed";
  }

  if (orderStatus === "shipping") {
    return "status-shipping";
  }

  if (orderStatus === "completed") {
    return "status-completed";
  }

  if (orderStatus === "cancelled") {
    return "status-cancelled";
  }

  return "status-default";
}

function getPaymentMethodText(paymentMethod) {
  if (paymentMethod === "cod") {
    return pText("paymentCod");
  }

  if (paymentMethod === "bank_transfer") {
    return pText("paymentBank");
  }

  return paymentMethod || "";
}

